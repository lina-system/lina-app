import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadThemes } from './design.mjs';
export const outputDirectory = 'packages/lina_app/macos/Runner/Launcher/Generated';
export function generateSwift(root) {
  const pin = JSON.parse(readFileSync(join(root, 'design/tokens/swift-upstream.json')));
  const dartPin = JSON.parse(readFileSync(join(root, 'design/tokens/upstream.json')));
  const core = readFileSync(join(root, 'design/tokens/core/tokens.swift'), 'utf8');
  if (pin.revision !== dartPin.revision || pin.repository !== dartPin.repository ||
      pin.path !== 'design/tokens/tokens.swift' || createHash('sha256').update(core).digest('hex') !== pin.sha256) {
    throw Error('Swift Core snapshot provenance mismatch');
  }
  const themes = loadThemes(root);
  const identifier = path => path.replace(/\.([a-z])/g, (_, x) => x.toUpperCase());
  const fields = Object.entries(themes[0].tokens).filter(([, t]) => ['dimension', 'number', 'fontFamily'].includes(t.$type));
  for (const [path, token] of fields) for (const theme of themes.slice(1)) {
    if (JSON.stringify(theme.tokens[path].$value) !== JSON.stringify(token.$value)) throw Error(`Swift constant varies by theme: ${path}`);
  }
  const values = fields.map(([path, t]) => {
    const v = t.$value;
    return `    public static let ${identifier(path)}${t.$type === 'fontFamily' ? ' = ' + JSON.stringify(v[0]) : ': CGFloat = ' + (t.$type === 'dimension' ? v.value : v)}`;
  }).join('\n');
  return {
    [`${outputDirectory}/LinaTokens.swift`]: core,
    [`${outputDirectory}/LinaAppTokens.swift`]: `// SPDX-License-Identifier: Apache-2.0\n// GENERATED by scripts/verify/swift-tokens.mjs from the same DTCG as lina_design.\nimport AppKit\n\npublic enum LinaAppTokens {\n${values}\n}\n`,
  };
}
export function checkSwift(root, outputs = generateSwift(root)) {
  if (existsSync(join(root, outputDirectory))) for (const file of readdirSync(join(root, outputDirectory), { recursive: true })) {
    if (!Object.hasOwn(outputs, `${outputDirectory}/${file}`)) throw Error(`unexpected Swift output: ${file}`);
  }
  for (const [path, content] of Object.entries(outputs)) {
    if (!existsSync(join(root, path)) || readFileSync(join(root, path), 'utf8') !== content) throw Error(`Swift generated drift: ${path}`);
  }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
  if (!['--check', '--write'].includes(process.argv[2])) throw Error('Use --check or --write');
  const outputs = generateSwift(root);
  if (process.argv[2] === '--check') checkSwift(root, outputs);
  else for (const [path, content] of Object.entries(outputs)) {
    mkdirSync(dirname(join(root, path)), { recursive: true }); writeFileSync(join(root, path), content);
  }
  console.log('Swift tokens: pinned Core output, shared app values and drift checked');
}
