// Writes native/LICENSES.md from `cargo metadata` and fails when a crate's
// license does not resolve to the permissive allow list.
// Usage (from native/): cargo metadata --locked --format-version 1 | node scripts/licenses.mjs > LICENSES.md

import { readFileSync } from "node:fs";

const ALLOWED = new Set([
  "Apache-2.0",
  "Apache-2.0 WITH LLVM-exception",
  "MIT",
  "MIT-0",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "0BSD",
  "ISC",
  "Zlib",
  "Unicode-3.0",
  "Unicode-DFS-2016",
  "BSL-1.0",
  "CC0-1.0",
  "Unlicense",
]);

// File-level copyleft: allowed to link, but listed for the owner's review.
const REVIEW = new Set(["MPL-2.0"]);
const COPYLEFT = /\b(A?GPL|LGPL|SSPL)/;

// An SPDX expression passes when one OR branch passes and every AND term of it passes.
function permissive(expression) {
  const cleaned = expression.replace(/[()]/g, " ").replace(/\//g, " OR ").trim();
  return cleaned
    .split(/\s+OR\s+/)
    .some((branch) => branch.split(/\s+AND\s+/).every((term) => ALLOWED.has(term.trim())));
}

const metadata = JSON.parse(readFileSync(0, "utf8"));
const workspace = new Set(metadata.workspace_members);
const byId = new Map(metadata.packages.map((pkg) => [pkg.id, pkg]));
const direct = new Map();
for (const id of workspace) {
  for (const dep of byId.get(id).dependencies) {
    if (dep.path) continue;
    direct.set(dep.name, (direct.get(dep.name) ?? new Set()).add(byId.get(id).name));
  }
}

const external = metadata.packages
  .filter((pkg) => !workspace.has(pkg.id))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true }));

const failures = [];
const review = [];
const row = (pkg) => {
  const license = pkg.license ?? (pkg.license_file ? `see ${pkg.license_file}` : "none");
  if (!pkg.license || !permissive(pkg.license)) {
    const reviewOnly = pkg.license && !COPYLEFT.test(pkg.license) && REVIEW.has(pkg.license.trim());
    (reviewOnly ? review : failures).push(`${pkg.name} ${pkg.version}: ${license}`);
  }
  const url = pkg.repository ?? pkg.homepage ?? `https://crates.io/crates/${pkg.name}`;
  return `| ${pkg.name} | ${pkg.version} | ${license.replace(/\|/g, "\\|")} | ${url} |`;
};

const lines = [
  "# Licenses of the native workspace's dependencies",
  "",
  "Generated by `native/scripts/licenses.mjs` from `cargo metadata --locked`. Do not edit by hand.",
  "",
  "The workspace's own crates (`lina-core`, `lina-native-app`) are Apache-2.0.",
  "",
  "## Direct dependencies",
  "",
  "| Crate | Version | SPDX | Upstream | Used by |",
  "| --- | --- | --- | --- | --- |",
];
for (const pkg of external.filter((each) => direct.has(each.name))) {
  lines.push(`${row(pkg)} ${[...direct.get(pkg.name)].join(", ")} |`);
}
lines.push(
  "",
  `## All resolved crates (${external.length}, every target platform in Cargo.lock)`,
  "",
  "| Crate | Version | SPDX | Upstream |",
  "| --- | --- | --- | --- |",
);
const seen = new Set();
for (const pkg of external) lines.push(row(pkg)) && seen.add(pkg.id);
const unique = [...new Set(failures)];
const toReview = [...new Set(review)];
lines.push(
  "",
  "## Check",
  "",
  unique.length === 0
    ? `No AGPL, GPL, LGPL or SSPL: all ${external.length} crates resolve to the permissive allow list in the script, except the MPL-2.0 crates below.`
    : `NOT PASSING: ${unique.length} crate(s) outside the allow list: ${unique.join("; ")}`,
  "",
  `MPL-2.0 (file-level copyleft, for review): ${toReview.length === 0 ? "none" : toReview.join("; ")}.`,
  "",
);
process.stdout.write(lines.join("\n"));
if (unique.length > 0) {
  console.error(`licenses: ${unique.length} crate(s) outside the allow list`);
  for (const failure of unique) console.error(`  ${failure}`);
  process.exit(1);
}
