import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';

const source = 'data/emoji/';
const output = 'packages/lina_app/macos/Runner/Launcher/Resources/emoji.json';
const manifest = JSON.parse(readFileSync(source + 'upstream.json'));
assert.deepEqual(readdirSync(source).sort(), [...Object.keys(manifest.files), 'upstream.json'].sort());
for (const [name, entry] of Object.entries(manifest.files)) {
  assert.equal(createHash('sha256').update(readFileSync(source + name)).digest('hex'), entry.sha256, `Unicode source drift: ${name}`);
}
const normalize = value => value.replaceAll('\uFE0F', '');
const skin = /[\u{1F3FB}-\u{1F3FF}]/gu;
const qualified = new Map();
for (const line of readFileSync(source + 'emoji-test.txt', 'utf8').split('\n')) {
  const match = line.match(/^([0-9A-F ]+)\s*; fully-qualified\s*#/);
  if (match) {
    const glyph = String.fromCodePoint(...match[1].trim().split(/\s+/).map(c => parseInt(c, 16)));
    qualified.set(normalize(glyph), glyph);
  }
}
const read = lang => Object.assign({}, ...['annotations', 'annotationsDerived'].map(kind =>
  JSON.parse(readFileSync(`${source}${kind}-${lang}.json`))[kind].annotations));
const en = read('en'), ko = read('ko');
const entries = Object.entries(en).filter(([glyph]) => !glyph.match(skin) && ko[glyph]?.tts?.[0]).map(([key, value]) => {
  assert.ok(ko[key]?.tts?.[0], `Missing Korean name for ${key}`);
  const glyph = qualified.get(normalize(key)) ?? key;
  const tones = Array.from({ length: 5 }, (_, i) => {
    const modifier = String.fromCodePoint(0x1F3FB + i);
    return [...qualified.values()].find(candidate => candidate.includes(modifier) &&
      [...candidate.matchAll(skin)].every(m => m[0] === modifier) &&
      normalize(candidate.replace(skin, '')) === normalize(key));
  });
  return { glyph, en: value.tts[0], ko: ko[key].tts[0],
    keywords: [...new Set([value.tts[0], ko[key].tts[0], ...(value.default ?? []), ...(ko[key].default ?? [])])],
    tones: tones.every(Boolean) ? tones : [] };
}).sort((a, b) => a.en < b.en ? -1 : a.en > b.en ? 1 : a.glyph < b.glyph ? -1 : 1);
const generated = JSON.stringify({ _comment: 'SPDX-License-Identifier: Apache-2.0; Unicode data: Unicode-3.0. Generated by scripts/verify/emoji.mjs.',
  cldr: manifest.cldr, unicode: manifest.unicode, entries }, null, 2) + '\n';
if (process.argv[2] === '--write') writeFileSync(output, generated);
else {
  assert.equal(process.argv[2], '--check', 'Use --write or --check');
  assert.equal(readFileSync(output, 'utf8'), generated, 'Emoji catalog drift; run node scripts/verify/emoji.mjs --write');
}
console.log(`emoji: ${entries.length} bilingual entries verified`);
